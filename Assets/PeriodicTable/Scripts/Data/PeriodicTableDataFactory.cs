        var list = new List<ElementEntry>(118);
        string[] names = GetArabicNames();
        string[] symbols = GetSymbols();
        string[] descriptions = GetArabicDescriptions();

        for (int i = 1; i <= 118; i++)
        {
            list.Add(new ElementEntry
            {
                atomicNumber = i,
                symbol = symbols[i],
                nameArabic = names[i],
                atomicMass = AtomicDataUtility.AtomicMasses[i],
                categoryArabic = AtomicDataUtility.CategoriesArabic[i],
                descriptionArabic = descriptions[i]
            });
        }

        return list;
    }

