    static readonly int[] ShellCapacity = { 2, 8, 18, 32, 32, 18, 8 };

    public static int[] GetElectronShells(int electronCount)
    {
        var shells = new List<int>();
        int remaining = electronCount;

        foreach (int capacity in ShellCapacity)
        {
            if (remaining <= 0) break;
            int count = Mathf.Min(remaining, capacity);
            shells.Add(count);
            remaining -= count;
        }

        return shells.ToArray();
    }

    public static string GetShellDistributionText(int electronCount)
    {
        int[] shells = GetElectronShells(electronCount);
        if (shells.Length == 0) return "-";

        var parts = new List<string>();
        var shellNames = new[] { "K", "L", "M", "N", "O", "P", "Q" };
        for (int i = 0; i < shells.Length; i++)
            parts.Add(shellNames[i] + ":" + shells[i]);

        return string.Join("  ", parts);
    }

